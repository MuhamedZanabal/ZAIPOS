import assert from 'node:assert/strict';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {connection,query} from './postgres-recovery.mjs';
if(!process.env.POSTGRES_ADMIN_URL)throw new Error('Disposable contract database required');
const conn=connection(process.env.POSTGRES_ADMIN_URL),sql=s=>query(conn,s);
const tenant='a8000000-0000-0000-0000-000000000001',branch='b8000000-0000-0000-0000-000000000001',user='c8000000-0000-0000-0000-000000000001',manager='c8000000-0000-0000-0000-000000000002',deviceUid='CASH-SESSION-BOUNDARY';
sql(`INSERT INTO auth.users(id,email,raw_user_meta_data) VALUES('${user}','cash-session-boundary@zaipos.test','{}'),('${manager}','cash-session-manager@zaipos.test','{}');
INSERT INTO public.tenants(id,name,slug,currency,tax_rate,dev_mode) VALUES('${tenant}','Session Boundary','session-boundary-contract','BHD',10,false);
INSERT INTO public.branches(id,tenant_id,name,status) VALUES('${branch}','${tenant}','Session Branch','active');
INSERT INTO public.user_roles(user_id,tenant_id,branch_id,role) VALUES('${user}','${tenant}','${branch}','cashier'),('${manager}','${tenant}','${branch}','manager');`);
const authAs=(actor,s,commit=false)=>sql(`BEGIN;SET LOCAL ROLE authenticated;SET LOCAL request.jwt.claim.sub='${actor}';${s};${commit?'COMMIT':'ROLLBACK'};`);
const auth=(s,commit=false)=>authAs(user,s,commit);
const approval=authAs(manager,`SELECT public.approve_device_enrollment('${tenant}','${branch}','${deviceUid}')::text`,true);
const credential=sql(`SET ROLE service_role;SELECT credential FROM public.activate_device_enrollment('${approval}','1.0.0','windows');RESET ROLE;`);
assert.match(credential,/^[a-f0-9]{64}$/i);
const open=(amount,operation='boundary-open-001')=>`SELECT public.open_cash_session_v2_device('${tenant}','${branch}',${amount},NULL,'${operation}','${deviceUid}','${credential}')::text`;
const failures=[];
function deny(label,s){try{auth(s);failures.push(label);console.log('UNSAFE: '+label);}catch{/* Statement must reject and roll back. */}}
deny('opening silently rounds fractional fils',open('1.0001'));
deny('opening accepts a negative physical float',open('-1.000'));
deny('opening treats omitted amount as zero',open('NULL'));
sql(`UPDATE auth.users SET banned_until=now()+interval '1 day' WHERE id='${user}'`);
deny('banned account opens a cash session',open('1.000'));
sql(`UPDATE auth.users SET banned_until=NULL WHERE id='${user}'`);
sql(`UPDATE public.branches SET status='inactive' WHERE id='${branch}'`);
deny('inactive branch accepts cash opening',open('1.000'));
sql(`UPDATE public.branches SET status='active' WHERE id='${branch}'`);
const session=auth(open('1.001'),true);assert.match(session,/^[a-f0-9-]{36}$/);
const close=(cash='1.001',card='0.000',operation='boundary-close-001')=>`SELECT public.close_cash_session_v2_device('${tenant}','${branch}','${session}',${cash},'Verified close',${card},0.000,0.000,'${operation}','${deviceUid}','${credential}')::text`;
deny('closing silently treats missing cash count as zero',close('NULL'));
deny('closing silently treats missing card count as zero',close('1.001','NULL'));
sql(`UPDATE auth.users SET banned_until=now()+interval '1 day' WHERE id='${user}'`);
deny('banned account closes a cash session',close());
sql(`UPDATE auth.users SET banned_until=NULL WHERE id='${user}'`);
assert.equal(failures.length,0,failures.join('; '));
assert.equal(sql(`SELECT opening_amount_fils FROM public.cash_sessions WHERE id='${session}'`),'1001');
assert.equal(sql(`SELECT count(*) FROM public.audit_logs WHERE entity_id='${session}' AND action='cash_session.opened'`),'1');
auth(close(),true);
assert.equal(sql(`SELECT difference_fils FROM public.cash_sessions WHERE id='${session}'`),'0');
// A failed audit must roll back opening rather than leave an unaudited till.
sql(`CREATE FUNCTION public.cash_open_audit_failure() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.action='cash_session.opened' AND NEW.tenant_id='${tenant}' THEN RAISE EXCEPTION 'Controlled audit failure'; END IF; RETURN NEW; END; $$;
CREATE TRIGGER cash_open_audit_failure BEFORE INSERT ON public.audit_logs FOR EACH ROW EXECUTE FUNCTION public.cash_open_audit_failure();`);
assert.throws(()=>auth(open('0.001','boundary-audit-failure'),true));
assert.equal(sql(`SELECT count(*) FROM public.cash_sessions WHERE branch_id='${branch}' AND status='open'`),'0');
sql('DROP TRIGGER cash_open_audit_failure ON public.audit_logs; DROP FUNCTION public.cash_open_audit_failure()');
const exec=promisify(execFile);
const race=await Promise.allSettled(Array.from({length:4},(_,index)=>exec('psql',['-X','-Atq','-v','ON_ERROR_STOP=1','-c',`BEGIN;SET LOCAL ROLE authenticated;SET LOCAL request.jwt.claim.sub='${user}';${open('0.001',`boundary-race-${index}`)};COMMIT;`],{env:conn.env,encoding:'utf8'})));
assert.equal(race.filter(r=>r.status==='fulfilled').length,1);
assert.equal(sql(`SELECT count(*) FROM public.cash_sessions WHERE branch_id='${branch}' AND status='open'`),'1');
assert.equal(sql(`SELECT count(*) FROM public.audit_logs WHERE metadata->>'branch_id'='${branch}' AND action='cash_session.opened'`),'2');
console.log('PASS: explicit exact-fils cash counts, current active account/branch and atomic opening audit required.');
